  src_coa_id              number,
  -- Target LE / Ledger / OU
  tgt_legal_entity_id     number,
  tgt_legal_entity_name   varchar2(240),
  tgt_ledger_id           number,
  tgt_ledger_name         varchar2(100),
  tgt_currency_code       varchar2(15),
  tgt_coa_id              number,
  tgt_org_id              number,
