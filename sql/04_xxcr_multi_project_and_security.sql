create or replace package body xxcr_security_pkg as

  c_application_id constant pls_integer := 600;

  procedure clear_http_state is
  begin
    apex_web_service.clear_request_headers;
    apex_web_service.clear_request_cookies;
    apex_web_service.g_headers.delete;
    apex_web_service.g_response_cookies.delete;
  end clear_http_state;

  function valid_username(p_username in varchar2) return boolean is
  begin
    return p_username is not null
       and length(p_username) <= 100
       and regexp_like(p_username, '^[A-Z0-9][A-Z0-9._@-]*$', 'c');
  end valid_username;

  function current_app_user return varchar2 is
  begin
    return upper(trim(coalesce(
      sys_context('APEX$SESSION', 'APP_USER'),
      apex_application.g_user,
      user
    )));
  end current_app_user;

  function app_enabled return boolean is
    l_cnt pls_integer;
  begin
    if apex_application.g_flow_id is not null and apex_application.g_flow_id <> c_application_id then
      return false;
    end if;
    select count(*)
      into l_cnt
      from xxcr_sec_config
     where application_id = c_application_id
       and enabled_yn = 'Y';
    return l_cnt = 1;
  end app_enabled;

  function provisioned(
    p_user  in varchar2,
    p_admin in boolean default false
  ) return boolean is
    l_cnt pls_integer;
  begin
    if not app_enabled or not valid_username(p_user) then
      return false;
    end if;
    select count(*)
      into l_cnt
      from xxcr_app_users
     where user_name = p_user
       and enabled_yn = 'Y'
       and (not p_admin or role_code = 'ROLLOUT_ADMIN');
    return l_cnt = 1;
  end provisioned;

  procedure record_login(
    p_user    in varchar2,
    p_code    in varchar2,
    p_details in varchar2 default null
  ) is
    pragma autonomous_transaction;
    l_actor   varchar2(100) := 'UNKNOWN';
    l_subject varchar2(100);
  begin
    if valid_username(p_user) then
      l_actor   := p_user;
      l_subject := p_user;
    end if;
    insert into xxcr_access_audit (actor, event_code, subject_user, details)
    values (l_actor, p_code, l_subject, substr(p_details, 1, 1000));
    commit;
  exception
    when others then
      rollback;
  end record_login;

  procedure log_security_event(
    p_event_code   in varchar2,
    p_subject_user in varchar2 default null,
    p_project_id   in number   default null,
    p_details      in varchar2 default null
  ) is
    l_actor varchar2(100) := nvl(current_app_user, 'SYSTEM');
  begin
    insert into xxcr_access_audit (actor, event_code, subject_user, project_id, details)
    values (l_actor, p_event_code, upper(trim(p_subject_user)), p_project_id, substr(p_details, 1, 1000));
  end log_security_event;

  procedure decode_login(
    p_response   in  clob,
    p_user       out varchar2,
    p_token_name out varchar2,
    p_token      out varchar2
  ) is
    l_root json_object_t;
    l_data json_object_t;
  begin
    if p_response is null then
      raise_application_error(-20510, 'Invalid EBS login response');
    end if;
    if regexp_like(ltrim(dbms_lob.substr(p_response, 20, 1)), '^<') then
      select x.user_name, x.token_name, x.token_value
        into p_user, p_token_name, p_token
        from xmltable(
               '/response/data'
               passing xmltype(p_response)
               columns
                 user_name   varchar2(4000) path 'userName',
                 token_name  varchar2(4000) path 'accessTokenName',
                 token_value varchar2(4000) path 'accessToken'
             ) x;
    else
      l_root       := json_object_t.parse(p_response);
      l_data       := l_root.get_object('data');
      p_user       := l_data.get_string('userName');
      p_token_name := l_data.get_string('accessTokenName');
      p_token      := l_data.get_string('accessToken');
    end if;
  end decode_login;

  function cookie_part_ok(
    p_value   in varchar2,
    p_is_name in boolean default false
  ) return boolean is
  begin
    return p_value is not null
       and length(p_value) <= 4000
       and instr(p_value, chr(10)) = 0
       and instr(p_value, chr(13)) = 0
       and instr(p_value, ';') = 0
       and instr(p_value, ',') = 0
       and not regexp_like(p_value, '[[:space:]]')
       and (not p_is_name or instr(p_value, '=') = 0);
  end cookie_part_ok;

  function validate_with_ebs(
    p_username in varchar2,
    p_password in varchar2
  ) return boolean is
    l_origin        xxcr_sec_config.ebs_origin%type;
    l_response      clob;
    l_status        pls_integer;
    l_user          varchar2(4000);
    l_token_name    varchar2(4000);
    l_token         varchar2(4000);
    l_cookie_header varchar2(32767);
    l_cookie_index  pls_integer;
    l_has_token     boolean := false;

    procedure append_cookie(p_name in varchar2, p_value in varchar2) is
    begin
      if not cookie_part_ok(p_name, true) or not cookie_part_ok(p_value) then
        raise_application_error(-20511, 'Invalid EBS cookie');
      end if;
      if l_cookie_header is not null then
        l_cookie_header := l_cookie_header || '; ';
      end if;
      l_cookie_header := l_cookie_header || p_name || '=' || p_value;
    end append_cookie;

    procedure end_remote_session is
      l_logout_response clob;
    begin
      clear_http_state;
      if l_cookie_header is not null then
        apex_web_service.g_request_headers(1).name  := 'Cookie';
        apex_web_service.g_request_headers(1).value := l_cookie_header;
        l_logout_response := apex_web_service.make_rest_request(
          p_url              => l_origin || '/OA_HTML/RF.jsp?function_id=mLogout',
          p_http_method      => 'GET',
          p_transfer_timeout => 15
        );
      end if;
      l_logout_response := null;
      clear_http_state;
    exception
      when others then
        clear_http_state;
    end end_remote_session;

  begin
    select ebs_origin
      into l_origin
      from xxcr_sec_config
     where application_id = c_application_id
       and enabled_yn = 'Y';

    if not regexp_like(l_origin, '^https://[A-Za-z0-9.-]+(:[0-9]+)?$', 'c') then
      return false;
    end if;

    clear_http_state;
    apex_web_service.g_request_headers(1).name  := 'Accept';
    apex_web_service.g_request_headers(1).value := 'application/json, application/xml';

    l_response := apex_web_service.make_rest_request(
      p_url              => l_origin || '/OA_HTML/RF.jsp?function_id=mLogin',
      p_http_method      => 'GET',
      p_username         => p_username,
      p_password         => p_password,
      p_scheme           => 'Basic',
      p_transfer_timeout => 20
    );
    l_status := apex_web_service.g_status_code;

    l_cookie_index := apex_web_service.g_response_cookies.first;
    while l_cookie_index is not null loop
      if apex_web_service.g_response_cookies(l_cookie_index).name is not null
         and apex_web_service.g_response_cookies(l_cookie_index).value is not null then
        append_cookie(
          apex_web_service.g_response_cookies(l_cookie_index).name,
          apex_web_service.g_response_cookies(l_cookie_index).value
        );
        if upper(apex_web_service.g_response_cookies(l_cookie_index).name) <> 'JSESSIONID' then
          l_has_token := true;
        end if;
      end if;
      l_cookie_index := apex_web_service.g_response_cookies.next(l_cookie_index);
    end loop;

    if l_status is null or l_status <> 200 then
      end_remote_session;
      return false;
    end if;

    decode_login(l_response, l_user, l_token_name, l_token);

    if l_token is not null and l_token <> '-1' then
      if l_token_name is null then
        raise_application_error(-20512, 'Invalid EBS token response');
      end if;
      append_cookie(l_token_name, l_token);
      l_has_token := true;
    end if;

    if l_user is null
       or upper(l_user) <> upper(trim(p_username))
       or l_token = '-1'
       or not l_has_token then
      end_remote_session;
      return false;
    end if;

    -- Immediately close remote EBS mobile/REST session; zero tokens or passwords persist
    end_remote_session;
    l_response      := null;
    l_token_name    := null;
    l_token         := null;
    l_cookie_header := null;
    return true;
  exception
    when others then
      end_remote_session;
      l_response      := null;
      l_token_name    := null;
      l_token         := null;
      l_cookie_header := null;
      clear_http_state;
      return false;
  end validate_with_ebs;

  function authenticate(
    p_username in varchar2,
    p_password in varchar2
  ) return boolean is
    l_user varchar2(32767) := upper(trim(p_username));
  begin
    if apex_application.g_flow_id is null or apex_application.g_flow_id <> c_application_id then
      return false;
    end if;

    if p_password is null or not provisioned(l_user) then
      record_login(l_user, 'LOGIN_DENIED', 'User not provisioned or disabled in XXCR_APP_USERS');
      return false;
    end if;

    if not validate_with_ebs(trim(p_username), p_password) then
      record_login(l_user, 'LOGIN_FAILED', 'EBS /OA_HTML/RF.jsp?function_id=mLogin rejected credentials');
      return false;
    end if;

    -- Re-verify provisioning in case access was revoked while EBS responded
    if not provisioned(l_user) then
      record_login(l_user, 'LOGIN_DENIED', 'User disabled during EBS verification');
      return false;
    end if;

    record_login(l_user, 'LOGIN_OK', 'Authenticated via EBS HTTPS mLogin');
    return true;
  exception
    when others then
      clear_http_state;
      record_login(l_user, 'LOGIN_ERROR', sqlerrm);
      return false;
  end authenticate;

  function effective_role(
    p_project_id in number   default null,
    p_user       in varchar2 default null
  ) return varchar2 is
    l_user          varchar2(100) := upper(trim(nvl(p_user, current_app_user)));
    l_global_role   xxcr_app_users.role_code%type;
    l_all_projects  xxcr_app_users.all_projects_yn%type;
    l_proj_role     xxcr_project_access.project_role_code%type;
    l_proj_enabled  xxcr_project_access.enabled_yn%type;
  begin
    if not app_enabled or not valid_username(l_user) then
      return null;
    end if;

    begin
      select role_code, all_projects_yn
        into l_global_role, l_all_projects
        from xxcr_app_users
       where user_name = l_user
         and enabled_yn = 'Y';
    exception
      when no_data_found then
        return null;
    end;

    -- Global Rollout Administrator always holds ROLLOUT_ADMIN across all projects
    if l_global_role = 'ROLLOUT_ADMIN' then
      return 'ROLLOUT_ADMIN';
    end if;

    -- If no project specified yet, return global role only when user has all_projects_yn='Y' or at least 1 active project grant
    if p_project_id is null then
      if l_all_projects = 'Y' then
        return l_global_role;
      end if;
      begin
        select project_role_code
          into l_proj_role
          from xxcr_project_access
         where user_name = l_user
           and enabled_yn = 'Y'
         fetch first 1 row only;
        return l_proj_role;
      exception
        when no_data_found then
          return null;
      end;
    end if;

    -- Check project-specific override / grant first
    begin
      select project_role_code, enabled_yn
        into l_proj_role, l_proj_enabled
        from xxcr_project_access
       where project_id = p_project_id
         and user_name = l_user;

      if l_proj_enabled = 'N' then
        return null;
      end if;
      return l_proj_role;
    exception
      when no_data_found then
        if l_all_projects = 'Y' then
          return l_global_role;
        else
          return null;
        end if;
    end;
  end effective_role;

  function role_label(p_role_code in varchar2) return varchar2 deterministic is
  begin
    return case p_role_code
      when 'ROLLOUT_ADMIN'    then 'Rollout Admin (IT / Lead)'
      when 'FINANCE_APPROVER' then 'Finance Approver (Checker)'
      when 'DATA_STEWARD'     then 'Data Steward (Maker)'
      when 'VIEWER'           then 'Read-Only Viewer'
      else 'No Access'
    end;
  end role_label;

  function can_access_app return boolean is
  begin
    return apex_application.g_flow_id = c_application_id
       and apex_authentication.is_authenticated
       and provisioned(current_app_user);
  end can_access_app;

  function is_admin return boolean is
  begin
    return apex_application.g_flow_id = c_application_id
       and apex_authentication.is_authenticated
       and provisioned(current_app_user, true);
  end is_admin;

  function resolve_active_project(p_requested_id in number default null) return number is
    l_user varchar2(100) := current_app_user;
    l_id   number;
  begin
    if p_requested_id is not null then
      select min(p.project_id)
        into l_id
        from xxcr_projects p
       where p.project_id = p_requested_id
         and effective_role(p.project_id, l_user) is not null;
      if l_id is not null then
        return l_id;
      end if;
    end if;

    select min(p.project_id)
      into l_id
      from xxcr_projects p
     where effective_role(p.project_id, l_user) is not null;

    return l_id;
  end resolve_active_project;

  function can_admin_project(p_project_id in number default null) return boolean is
    l_proj_id number := resolve_active_project(p_project_id);
  begin
    return can_access_app
       and l_proj_id is not null
       and effective_role(l_proj_id, current_app_user) = 'ROLLOUT_ADMIN';
  end can_admin_project;

  function can_view_project(p_project_id in number default null) return boolean is
    l_proj_id number := resolve_active_project(p_project_id);
  begin
    return can_access_app
       and l_proj_id is not null
       and effective_role(l_proj_id, current_app_user) is not null;
  end can_view_project;

  function can_edit_data(p_project_id in number default null) return boolean is
    l_proj_id number := resolve_active_project(p_project_id);
  begin
    return can_access_app
       and l_proj_id is not null
       and effective_role(l_proj_id, current_app_user) in ('ROLLOUT_ADMIN', 'DATA_STEWARD');
  end can_edit_data;

  function can_approve_finance(p_project_id in number default null) return boolean is
    l_proj_id number := resolve_active_project(p_project_id);
  begin
    return can_access_app
       and l_proj_id is not null
       and effective_role(l_proj_id, current_app_user) in ('ROLLOUT_ADMIN', 'FINANCE_APPROVER');
  end can_approve_finance;

  function can_edit_or_approve(p_project_id in number default null) return boolean is
    l_proj_id number := resolve_active_project(p_project_id);
  begin
    return can_access_app
       and l_proj_id is not null
       and effective_role(l_proj_id, current_app_user) in ('ROLLOUT_ADMIN', 'DATA_STEWARD', 'FINANCE_APPROVER');
  end can_edit_or_approve;

  procedure save_user(
    p_username        in varchar2,
    p_role_code       in varchar2,
    p_all_projects_yn in varchar2 default 'Y',
    p_enabled_yn      in varchar2 default 'Y',
    p_full_name       in varchar2 default null,
    p_email_address   in varchar2 default null,
    p_notes           in varchar2 default null
  ) is
    l_user         varchar2(32767) := upper(trim(p_username));
    l_actor        varchar2(100)   := current_app_user;
    l_all_proj     varchar2(1)     := case when upper(trim(p_all_projects_yn)) = 'N' then 'N' else 'Y' end;
    l_enabled      varchar2(1)     := case when upper(trim(p_enabled_yn)) = 'N' then 'N' else 'Y' end;
    l_full_name    varchar2(240)   := trim(p_full_name);
    l_email        varchar2(240)   := trim(p_email_address);
    l_other_admins pls_integer;
  begin
    if not is_admin then
      raise_application_error(-20520, 'Rollout Administrator access is required to manage users.');
    end if;

    if not valid_username(l_user)
       or p_role_code is null
       or p_role_code not in ('ROLLOUT_ADMIN', 'FINANCE_APPROVER', 'DATA_STEWARD', 'VIEWER') then
      raise_application_error(-20521, 'Enter a valid EBS username and SoD role (ROLLOUT_ADMIN, FINANCE_APPROVER, DATA_STEWARD, or VIEWER).');
    end if;

    if p_role_code = 'ROLLOUT_ADMIN' then
      l_all_proj := 'Y';
    end if;

    -- Optional non-blocking enrichment of Full Name & Email from EBS FND_USER@ADG when blank
    if l_full_name is null or l_email is null then
      begin
        select /*+ driving_site(fu) */
               nvl(l_full_name, substr(fu.description, 1, 240)),
               nvl(l_email, substr(fu.email_address, 1, 240))
          into l_full_name, l_email
          from apps.fnd_user@adg fu
         where fu.user_name = l_user
         fetch first 1 row only;
      exception
        when others then
          null;
      end;
    end if;

    -- Serialize user table updates to prevent locking out the last active ROLLOUT_ADMIN
    lock table xxcr_app_users in exclusive mode wait 10;

    if not is_admin then
      raise_application_error(-20520, 'Rollout Administrator access is required to manage users.');
    end if;

    if l_user = l_actor and (p_role_code <> 'ROLLOUT_ADMIN' or l_enabled <> 'Y') then
      raise_application_error(-20522, 'Anti-Lockout Guard: You cannot disable or demote your own Rollout Administrator account.');
    end if;

    if p_role_code <> 'ROLLOUT_ADMIN' or l_enabled <> 'Y' then
      select count(*)
        into l_other_admins
        from xxcr_app_users
       where user_name <> l_user
         and role_code = 'ROLLOUT_ADMIN'
         and enabled_yn = 'Y';
      if l_other_admins = 0 then
        raise_application_error(-20523, 'Anti-Lockout Guard: At least one active ROLLOUT_ADMIN user must remain enabled.');
      end if;
    end if;

    merge into xxcr_app_users t
    using (select l_user as user_name from dual) s
       on (t.user_name = s.user_name)
     when matched then
       update set
         role_code       = p_role_code,
         all_projects_yn = l_all_proj,
         enabled_yn      = l_enabled,
         full_name       = coalesce(l_full_name, t.full_name),
         email_address   = coalesce(l_email, t.email_address),
         notes           = coalesce(trim(p_notes), t.notes),
         updated_at      = systimestamp,
         updated_by      = l_actor
     when not matched then
       insert (
         user_name, full_name, email_address, role_code,
         all_projects_yn, enabled_yn, notes, created_by, updated_by
       ) values (
         l_user, l_full_name, l_email, p_role_code,
         l_all_proj, l_enabled, trim(p_notes), l_actor, l_actor
       );

    log_security_event(
      p_event_code   => 'USER_ROLE_SAVED',
      p_subject_user => l_user,
      p_details      => 'Role=' || p_role_code || '; all_projects=' || l_all_proj || '; enabled=' || l_enabled
    );
  end save_user;

  procedure save_project_access(
    p_project_id        in number,
    p_username          in varchar2,
    p_project_role_code in varchar2,
    p_enabled_yn        in varchar2 default 'Y',
    p_notes             in varchar2 default null
  ) is
    l_user    varchar2(100) := upper(trim(p_username));
    l_actor   varchar2(100) := current_app_user;
    l_enabled varchar2(1)   := case when upper(trim(p_enabled_yn)) = 'N' then 'N' else 'Y' end;
    l_cnt     pls_integer;
  begin
    if not is_admin then
      raise_application_error(-20520, 'Rollout Administrator access is required to assign project roles.');
    end if;

    if p_project_id is null
       or not valid_username(l_user)
       or p_project_role_code is null
       or p_project_role_code not in ('ROLLOUT_ADMIN', 'FINANCE_APPROVER', 'DATA_STEWARD', 'VIEWER') then
      raise_application_error(-20524, 'Select a valid Conversion Project, EBS User, and Project Role.');
    end if;

    select count(*) into l_cnt from xxcr_app_users where user_name = l_user;
    if l_cnt = 0 then
      raise_application_error(-20525, 'Add EBS user "' || l_user || '" on Tab 1 (EBS Users & Global Roles) before granting per-project overrides.');
    end if;

    merge into xxcr_project_access t
    using (select p_project_id as project_id, l_user as user_name from dual) s
       on (t.project_id = s.project_id and t.user_name = s.user_name)
     when matched then
       update set
         project_role_code = p_project_role_code,
         enabled_yn        = l_enabled,
         notes             = coalesce(trim(p_notes), t.notes),
         updated_at        = systimestamp,
         updated_by        = l_actor
     when not matched then
       insert (
         project_id, user_name, project_role_code, enabled_yn, notes, created_by, updated_by
       ) values (
         p_project_id, l_user, p_project_role_code, l_enabled, trim(p_notes), l_actor, l_actor
       );

    log_security_event(
      p_event_code   => 'PROJECT_ACCESS_SAVED',
      p_subject_user => l_user,
      p_project_id   => p_project_id,
      p_details      => 'ProjectRole=' || p_project_role_code || '; enabled=' || l_enabled
    );
  end save_project_access;

  procedure save_ebs_origin(
    p_ebs_origin in varchar2,
    p_enabled_yn in varchar2 default 'Y'
  ) is
    l_origin  varchar2(255) := rtrim(trim(p_ebs_origin), '/');
    l_enabled varchar2(1)   := case when upper(trim(p_enabled_yn)) = 'N' then 'N' else 'Y' end;
    l_actor   varchar2(100) := current_app_user;
  begin
    if not is_admin then
      raise_application_error(-20520, 'Rollout Administrator access is required to update EBS Auth Origin.');
    end if;

    if l_origin is null or not regexp_like(l_origin, '^https://[A-Za-z0-9.-]+(:[0-9]+)?$', 'c') then
      raise_application_error(-20526, 'EBS Origin must be a clean HTTPS host origin (for example: https://erpdev4tex.terex.com).');
    end if;

    update xxcr_sec_config
       set ebs_origin = l_origin,
           enabled_yn = l_enabled,
           updated_by = l_actor,
           updated_at = systimestamp
     where application_id = c_application_id;

    log_security_event(
      p_event_code => 'EBS_ORIGIN_SAVED',
      p_details    => 'Origin=' || l_origin || '; enabled=' || l_enabled
    );
  end save_ebs_origin;

