-- 1. EBS Authentication Configuration (App 600)
declare
  l_cnt number;
begin
  select count(*) into l_cnt from user_tables where table_name = 'XXCR_SEC_CONFIG';
  if l_cnt = 0 then
    execute immediate q'[
      create table xxcr_sec_config (
        application_id  number        primary key,
        ebs_origin      varchar2(255) not null,
        enabled_yn      varchar2(1)   default 'Y' not null,
        updated_by      varchar2(100) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
        updated_at      timestamp with time zone default systimestamp not null,
        constraint xxcr_sec_config_ck1 check (enabled_yn in ('Y', 'N')),
        constraint xxcr_sec_config_ck2 check (regexp_like(ebs_origin, '^https://[A-Za-z0-9.-]+(:[0-9]+)?$', 'c'))
      )
    ]';
  end if;
end;
