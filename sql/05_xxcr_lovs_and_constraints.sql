-- 1. Cached EBS Reference Lookups Table (Populated Read-Only from @ADG)
declare
  l_cnt number;
begin
  select count(*) into l_cnt from user_tables where table_name = 'XXCR_EBS_REF_LOVS';
  if l_cnt = 0 then
    execute immediate q'[
      create table xxcr_ebs_ref_lovs (
        lov_id         number generated by default on null as identity primary key,
        domain_code    varchar2(40)  not null,
        org_id         number,
        return_value   varchar2(240) not null,
        display_value  varchar2(500) not null,
        extra_info     varchar2(240),
        active_yn      varchar2(1)   default 'Y' not null,
        updated_at     timestamp with time zone default systimestamp not null
      )
    ]';
    execute immediate 'create unique index xxcr_ebs_ref_lovs_uk1 on xxcr_ebs_ref_lovs(domain_code, nvl(org_id, -1), return_value)';
    execute immediate 'create index xxcr_ebs_ref_lovs_ix1 on xxcr_ebs_ref_lovs(domain_code, active_yn, display_value)';
  end if;
end;
/

-- 2. Normalize Any Legacy Whitespace / Casing Before Adding Hard CHECK Constraints
begin
  update xxcr_stg_customers
     set include_yn               = case when upper(trim(include_yn)) = 'N' then 'N' else 'Y' end,
         action_code              = case when upper(trim(action_code)) in ('EXTEND_OU', 'NEW_ACCT', 'SKIP') then upper(trim(action_code)) else 'EXTEND_OU' end,
         tgt_credit_currency      = upper(trim(tgt_credit_currency)),
         tgt_overall_credit_limit = case when tgt_overall_credit_limit < 0 then 0 else tgt_overall_credit_limit end,
         tgt_trx_credit_limit     = case when tgt_trx_credit_limit < 0 then 0 else tgt_trx_credit_limit end;

  update xxcr_stg_sites
     set include_yn  = case when upper(trim(include_yn)) = 'N' then 'N' else 'Y' end,
         tgt_country = upper(trim(tgt_country));

  update xxcr_stg_site_uses
     set include_yn               = case when upper(trim(include_yn)) = 'N' then 'N' else 'Y' end,
         tgt_primary_flag         = case when upper(trim(tgt_primary_flag)) = 'Y' then 'Y' else 'N' end,
         tgt_site_use_code        = upper(trim(tgt_site_use_code)),
         tgt_credit_currency      = upper(trim(tgt_credit_currency)),
         tgt_overall_credit_limit = case when tgt_overall_credit_limit < 0 then 0 else tgt_overall_credit_limit end,
         tgt_trx_credit_limit     = case when tgt_trx_credit_limit < 0 then 0 else tgt_trx_credit_limit end;

  update xxcr_stg_contacts
     set include_yn        = case when upper(trim(include_yn)) = 'N' then 'N' else 'Y' end,
         tgt_primary_flag  = case when upper(trim(tgt_primary_flag)) = 'Y' then 'Y' else 'N' end,
         tgt_email_address = lower(trim(tgt_email_address));

  update xxcr_duplicates
     set resolution_action = case
                               when upper(trim(resolution_action)) in ('OPEN', 'EXCLUDE_DUPLICATE', 'REUSE_EXISTING', 'KEEP_BOTH_OVERRIDE')
                               then upper(trim(resolution_action))
                               else 'OPEN'
                             end;

  update xxcr_val_errors
     set ack_yn = case when upper(trim(ack_yn)) = 'Y' then 'Y' else 'N' end;

  commit;
end;
