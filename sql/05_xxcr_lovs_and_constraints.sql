-- 3. Add Idempotent Hard Database CHECK Constraints Across All Staging & Triage Tables
declare
  procedure add_chk(p_table in varchar2, p_cname in varchar2, p_expr in varchar2) is
    l_cnt number;
  begin
    select count(*)
      into l_cnt
      from user_constraints
     where table_name = upper(p_table)
       and constraint_name = upper(p_cname);
    if l_cnt = 0 then
      execute immediate 'alter table ' || p_table || ' add constraint ' || p_cname || ' check (' || p_expr || ')';
    end if;
  end add_chk;
begin
  -- XXCR_STG_CUSTOMERS
  add_chk('xxcr_stg_customers', 'xxcr_stg_cust_inc_ck',  q'[include_yn in ('Y', 'N')]');
  add_chk('xxcr_stg_customers', 'xxcr_stg_cust_act_ck',  q'[action_code in ('EXTEND_OU', 'NEW_ACCT', 'SKIP')]');
  add_chk('xxcr_stg_customers', 'xxcr_stg_cust_ocl_ck',  q'[tgt_overall_credit_limit is null or tgt_overall_credit_limit >= 0]');
  add_chk('xxcr_stg_customers', 'xxcr_stg_cust_tcl_ck',  q'[tgt_trx_credit_limit is null or tgt_trx_credit_limit >= 0]');

  -- XXCR_STG_SITES
  add_chk('xxcr_stg_sites',     'xxcr_stg_site_inc_ck',  q'[include_yn in ('Y', 'N')]');

  -- XXCR_STG_SITE_USES
  add_chk('xxcr_stg_site_uses', 'xxcr_stg_su_inc_ck',    q'[include_yn in ('Y', 'N')]');
  add_chk('xxcr_stg_site_uses', 'xxcr_stg_su_prim_ck',   q'[tgt_primary_flag is null or tgt_primary_flag in ('Y', 'N')]');
  add_chk('xxcr_stg_site_uses', 'xxcr_stg_su_code_ck',   q'[tgt_site_use_code in ('BILL_TO', 'SHIP_TO', 'STMTS', 'DUN', 'LEGAL', 'SOLD_TO')]');
  add_chk('xxcr_stg_site_uses', 'xxcr_stg_su_ocl_ck',    q'[tgt_overall_credit_limit is null or tgt_overall_credit_limit >= 0]');
  add_chk('xxcr_stg_site_uses', 'xxcr_stg_su_tcl_ck',    q'[tgt_trx_credit_limit is null or tgt_trx_credit_limit >= 0]');

  -- XXCR_STG_CONTACTS
  add_chk('xxcr_stg_contacts',  'xxcr_stg_cnt_inc_ck',   q'[include_yn in ('Y', 'N')]');
  add_chk('xxcr_stg_contacts',  'xxcr_stg_cnt_prim_ck',  q'[tgt_primary_flag is null or tgt_primary_flag in ('Y', 'N')]');

  -- XXCR_DUPLICATES & XXCR_VAL_ERRORS
  add_chk('xxcr_duplicates',    'xxcr_dups_res_ck',      q'[resolution_action in ('OPEN', 'EXCLUDE_DUPLICATE', 'REUSE_EXISTING', 'KEEP_BOTH_OVERRIDE')]');
  add_chk('xxcr_val_errors',    'xxcr_val_err_ack_ck',   q'[ack_yn in ('Y', 'N')]');
end;
/

-- 4. Row-Level Normalization & Immutable-Key Guard Triggers
create or replace trigger xxcr_stg_cust_biu_trg
before insert or update on xxcr_stg_customers
for each row
begin
  :new.include_yn              := upper(trim(nvl(:new.include_yn, 'Y')));
  :new.action_code             := upper(trim(nvl(:new.action_code, 'EXTEND_OU')));
  :new.tgt_party_name          := trim(:new.tgt_party_name);
  :new.tgt_account_name        := trim(:new.tgt_account_name);
  :new.tgt_tax_reference       := trim(:new.tgt_tax_reference);
  :new.tgt_customer_class_code := trim(:new.tgt_customer_class_code);
  :new.tgt_profile_class_name  := trim(:new.tgt_profile_class_name);
  :new.tgt_collector_name      := trim(:new.tgt_collector_name);
  :new.tgt_payment_term_name   := trim(:new.tgt_payment_term_name);
  :new.tgt_credit_currency     := upper(trim(:new.tgt_credit_currency));

  -- Immutable Account Number Guard when extending an existing EBS Customer Account
  if :new.action_code = 'EXTEND_OU' and :new.src_account_number is not null then
    :new.tgt_account_number := :new.src_account_number;
  else
    :new.tgt_account_number := trim(:new.tgt_account_number);
  end if;

  -- Keep Immutable Source / System Columns Locked During Updates
  if updating then
    :new.scope_class := :old.scope_class;
  end if;
end;
/

